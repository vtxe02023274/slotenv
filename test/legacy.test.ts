import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";
import { up } from "../src/core.js";
import { renderEnv } from "../src/env.js";
import { HOOK_BLOCK, hookPath, installHook, uninstallHook } from "../src/hook.js";
import { homeDir } from "../src/registry.js";
import { addWorktree, freeBase, runCli, sandbox } from "./helpers.js";

const LEGACY_BLOCK = [
  "# >>> nocollide >>>",
  'case "$1" in',
  "  *[!0]*) ;;",
  "  *) nocollide up || true ;;",
  "esac",
  "# <<< nocollide <<<",
].join("\n");

test("a nocollide.json from before the rename still works", async (t) => {
  const base = await freeBase();
  const box = sandbox({
    "nocollide.json": JSON.stringify({ ports: { WEB_PORT: base }, env: { from: ".env.example", to: ".env.local" } }),
    ".env.example": "DB_NAME=app_s${NOCOLLIDE_SLOT}\n",
  });
  t.after(box.cleanup);
  const worktree = addWorktree(box, "old");
  const claim = await up(worktree);
  assert.equal(claim.slot, 1);
  const env = readFileSync(join(worktree, ".env.local"), "utf8");
  assert.match(env, /^DB_NAME=app_s1$/m);
  assert.match(env, /^SLOTENV_SLOT=1$/m);
  const doctor = await runCli(box.repo, ["doctor"], box.home);
  assert.match(doctor.stdout, /Rename nocollide\.json to slotenv\.json/);
  const init = await runCli(box.repo, ["init"], box.home);
  assert.match(init.stderr, /nocollide\.json already exists/);
});

test("an env file written by nocollide is still recognized and replaced", () => {
  const output = renderEnv("# Generated by nocollide. Slot 1.\nA=1\n", { WEB_PORT: "3010" }, 1);
  assert.equal(output.match(/Generated by/g)?.length, 1);
  assert.ok(output.startsWith("# Generated by slotenv."));
});

test("hook install replaces a nocollide hook block and uninstall removes it", (t) => {
  const box = sandbox();
  t.after(box.cleanup);
  const file = hookPath(box.repo);
  writeFileSync(file, `#!/bin/sh\n${LEGACY_BLOCK}\necho mine\n`);
  assert.equal(installHook(box.repo).updated, true);
  assert.equal(readFileSync(file, "utf8"), `#!/bin/sh\n${HOOK_BLOCK}\necho mine\n`);
  writeFileSync(file, `#!/bin/sh\n${LEGACY_BLOCK}\necho mine\n`);
  assert.deepEqual(uninstallHook(box.repo), { file, removed: true, deleted: false });
  assert.equal(readFileSync(file, "utf8"), "#!/bin/sh\necho mine\n");
});

test("NOCOLLIDE_HOME is still honored", (t) => {
  const box = sandbox();
  t.after(box.cleanup);
  const saved = process.env.SLOTENV_HOME;
  delete process.env.SLOTENV_HOME;
  process.env.NOCOLLIDE_HOME = join(box.dir, "old-home");
  t.after(() => {
    delete process.env.NOCOLLIDE_HOME;
    process.env.SLOTENV_HOME = saved;
  });
  assert.equal(homeDir(), join(box.dir, "old-home"));
});
